def format_detail(result: Dict[str, Any]) -> str:
    lines = [
        f"{result['verdict']}  {result['score']}/100  {result['title']}",
        f"  {result['url']}",
        f"  repo: {result['repo']}  stars: {result['repo_stars']}  forks: {result['repo_forks']}"
        f"  license: {result['repo_license'] or 'none'}",
        f"  reward: {'${:,}'.format(result['amount_usd']) if result['amount_usd'] else 'none stated'}"
        f"  token-like: {'yes' if result['token_reward'] else 'no'}"
        f"  escrow: {result['escrow'] or 'none detected'}",
        f"  competition: {result['comment_count']} comments, {result['claimants']} claim(s),"
        f" {result['open_prs']} open PR(s)",
        f"  AI policy: {result['ai_policy']}"
        + (f" ({result['ai_policy_evidence']})" if result["ai_policy_evidence"] else ""),
    ]
    if result["updated_days"] is not None:
        lines.insert(5, f"  last updated: {result['updated_days']} day(s) ago")
    lines.append("  reasons:")
    for reason in result["reasons"]:
        lines.append(f"    {reason['delta']:+4d}  {reason['reason']}")
    return "\n".join(lines)


def format_table(results: List[Dict[str, Any]]) -> str:
    header = f"{'SCORE':>5}  {'VERDICT':8}  {'USD':>7}  {'CLAIMS':>6}  {'CMTS':>5}  TITLE"
    rows = [header, "-" * len(header)]
    for result in results:
        title = (result["title"] or "")[:58]
        rows.append(
            f"{result['score']:>5}  {result['verdict']:8}  "
            f"{result['amount_usd']:>7,}  {result['claimants']:>6}  {result['comment_count']:>5}  {title}"
        )
    return "\n".join(rows)


