def analyse(client: GitHub, owner: str, repo_name: str, number: int) -> Dict[str, Any]:
    issue = client.issue(owner, repo_name, number)
    if "pull_request" in issue:
        raise GitHubError("that URL is a pull request, not an issue")
    repo = client.repository(owner, repo_name)
    comments = client.comments(owner, repo_name, number)
    open_prs = client.open_pull_requests(owner, repo_name, number)

    documents = {path: client.file_text(owner, repo_name, path) for path in POLICY_FILES}
    policy, policy_evidence = classify_ai_policy(documents)

    text = f"{issue.get('title') or ''}\n{issue.get('body') or ''}"
    amount = parse_amount(text)
    token_reward = looks_like_token_reward(text)
    escrow = find_escrow(comments, text)
    repo_age = days_since(repo.get("created_at"))

    signals = {
        "amount_usd": amount,
        "token_reward": token_reward,
        "escrow": escrow,
        "is_open": issue.get("state") == "open",
        "repo_adjustments": repo_health(repo, repo_age),
        "comment_count": int(issue.get("comments") or 0),
        "open_prs": open_prs,
        "claimants": count_claim_comments(comments),
        "updated_days": days_since(issue.get("updated_at")),
        "ai_policy": policy,
    }
    result = score_issue(signals)
    result.update(
        {
            "url": issue.get("html_url"),
            "title": issue.get("title"),
            "repo": f"{owner}/{repo_name}",
            "labels": [label.get("name") for label in issue.get("labels") or []],
            "amount_usd": amount,
            "token_reward": token_reward,
            "escrow": escrow,
            "ai_policy": policy,
            "ai_policy_evidence": policy_evidence,
            "repo_stars": int(repo.get("stargazers_count") or 0),
            "repo_forks": int(repo.get("forks_count") or 0),
            "repo_license": (repo.get("license") or {}).get("spdx_id"),
            "comment_count": signals["comment_count"],
            "open_prs": open_prs,
            "claimants": signals["claimants"],
            "updated_days": signals["updated_days"],
        }
    )
    return result


