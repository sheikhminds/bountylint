def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="bountylint",
        description="Score a GitHub bounty issue before you spend time on it.",
    )
    parser.add_argument("target", nargs="?", help="issue URL or owner/repo#123")
    parser.add_argument("--search", metavar="QUERY", help="GitHub issue-search query to scan")
    parser.add_argument("--limit", type=int, default=10, help="max issues to analyse in search mode")
    parser.add_argument("--min-score", type=int, default=0, help="hide results below this score")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    parser.add_argument("--token", help="GitHub token (defaults to env or .env)")
    parser.add_argument("--timeout", type=int, default=25, help="HTTP timeout in seconds")
    parser.add_argument("--version", action="version", version=f"bountylint {__version__}")
    args = parser.parse_args(argv)

    if not args.target and not args.search:
        parser.error("give an issue URL/owner-repo#number, or --search QUERY")

    client = GitHub(token=args.token, timeout=args.timeout)
    try:
        if args.search:
            issues = client.search_issues(args.search, args.limit)
            results = []
            for item in issues:
                match = re.search(r"/([^/]+)/([^/]+)/issues/([0-9]+)$", item.get("html_url") or "")
                if not match:
                    continue
                owner, repo_name, number = match.group(1), match.group(2), int(match.group(3))
                try:
                    results.append(analyse(client, owner, repo_name, number))
                except GitHubError as exc:
                    print(f"skip {owner}/{repo_name}#{number}: {exc}", file=sys.stderr)
            results = [r for r in results if r["score"] >= args.min_score]
            results.sort(key=lambda r: (-r["score"], -r["amount_usd"]))
            if args.json:
                print(json.dumps(results, indent=2))
            elif results:
                print(format_table(results))
                print(f"\n{len(results)} issue(s) analysed. Use a URL for full reasons.")
            else:
                print("No issues matched.")
            return 0

        owner, repo_name, number = parse_issue_reference(args.target)
        if number is None:
            parser.error("expected an issue number, e.g. owner/repo#123")
        result = analyse(client, owner, repo_name, number)
        if args.json:
            print(json.dumps(result, indent=2))
        else:
            print(format_detail(result))
        return 0
    except (GitHubError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
