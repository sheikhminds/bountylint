#!/usr/bin/env python3
"""bountylint  -  decide whether a GitHub bounty is worth your time.

Built and maintained by an autonomous AI agent.

Reads only public GitHub REST data. Deterministic scoring: same issue, same score.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from typing import Any, Dict, Iterable, List, Optional, Tuple

__version__ = "0.1.0"

API = "https://api.github.com"
USER_AGENT = f"bountylint/{__version__}"
TOKEN_ENV_VARS = ("BOUNTYLINT_TOKEN", "GITHUB_TOKEN", "GITHUB_ACCESS_TOKEN", "GH_TOKEN")

# Money mentioned in a bounty issue: "$9k", "US$ 2,340", "750 USD", "$150.00"
CASH_RE = re.compile(
    r"(?:US)?\$\s?([0-9][0-9,]*(?:\.[0-9]{1,2})?)(?:\s*([kK]))?"
    r"|([0-9][0-9,]*(?:\.[0-9]{1,2})?)\s?(?:USD|usd)\b"
)
# A ticker reward, e.g. "$ROBIN_MCP", "$ARB"  -  an uppercase symbol right after a dollar sign.
TICKER_RE = re.compile(r"\$\s?([A-Z][A-Z0-9_]{1,12})\b")
TOKEN_WORDS = (
    "in tokens",
    "token reward",
    "paid in tokens",
    "airdropped",
    "airdrop",
    "points reward",
    "rewards in points",
    "nft reward",
    "in nft",
    "rtc",
    "memecoin",
)
ESCROW_BOTS = (
    "algora-pbc",
    "issuehunt",
    "opire",
    "polar-sh",
    "gitcoinco",
    "bountysource",
    "gitpay",
    "swe-bench-bounties",
)
ESCROW_TEXT = (
    "escrowed",
    "bounty is funded",
    "funded via algora",
    "funded on algora",
    "posted on issuehunt",
    "via opire",
    "polar.sh",
)
CLAIM_PATTERNS = (
    "/claim",
    "/attempt",
    "/try",
    "i'll take this",
    "i will take this",
    "i am working on this",
    "i'm working on this",
    "assign me",
    "can i work on this",
    "i would like to work on this",
    "dibs",
    "working on a pr",
)
AI_RESTRICTIVE = (
    "no ai-generated",
    "no ai generated",
    "ai-generated contributions are not",
    "do not submit ai",
    "no llm",
    "llm-generated",
    "generated by ai",
    "ai slop",
    "not accept ai",
    "prohibit ai",
    "forbid ai",
    "ban ai",
    "no chatgpt",
    "no copilot",
    "do not use ai",
)
AI_PERMISSIVE = (
    "ai agents welcome",
    "welcome ai-assisted",
    "ai-assisted contributions are welcome",
    "autonomous agents are welcome",
    "ai contributions are welcome",
    "ai-generated code is allowed",
)
POLICY_FILES = (
    "CONTRIBUTING.md",
    ".github/CONTRIBUTING.md",
    "README.md",
    ".github/PULL_REQUEST_TEMPLATE.md",
    "AGENTS.md",
)


# ---------------------------------------------------------------------------
# Pure helpers (no network, covered by tests)
# ---------------------------------------------------------------------------


def parse_amount(text: Optional[str]) -> int:
    """Largest plausible USD amount found in text, as an int. 0 when none."""
    if not text:
        return 0
    best = 0
    for match in CASH_RE.finditer(text):
        raw = match.group(1) or match.group(3) or ""
        raw = raw.replace(",", "")
        if not raw:
            continue
        try:
            value = float(raw)
        except ValueError:
            continue
        if match.group(2):
            value *= 1000
        value = int(round(value))
        if 5 <= value <= 500_000 and value > best:
            best = value
    return best


def looks_like_token_reward(text: Optional[str]) -> bool:
    """True when the reward is paid in a project token/points rather than cash."""
    if not text:
        return False
    lowered = text.lower()
    if any(word in lowered for word in TOKEN_WORDS):
        return True
    for match in TICKER_RE.finditer(text):
        ticker = match.group(1)
        # Ignore obvious non-tickers such as $USD, $USDC, $EUR.
        if ticker in {"USD", "USDC", "USDT", "EUR", "GBP", "AUD", "CAD"}:
            continue
        if len(ticker) >= 3:
            return True
    return False


def parse_issue_reference(value: str) -> Tuple[str, str, Optional[int]]:
    """Accept a URL, `owner/repo#12`, or `owner/repo` and return (owner, repo, number)."""
    value = value.strip()
    url_match = re.search(
        r"github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)/(?:issues|pull)/([0-9]+)", value
    )
    if url_match:
        return url_match.group(1), url_match.group(2), int(url_match.group(3))
    hash_match = re.fullmatch(r"([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)#([0-9]+)", value)
    if hash_match:
        return hash_match.group(1), hash_match.group(2), int(hash_match.group(3))
    repo_match = re.fullmatch(r"([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)", value)
    if repo_match:
        return repo_match.group(1), repo_match.group(2), None
    raise ValueError(f"cannot parse issue reference: {value!r}")


def days_since(stamp: Optional[str], now: Optional[datetime] = None) -> Optional[int]:
    """Whole days between an ISO-8601 GitHub timestamp and now."""
    if not stamp:
        return None
    now = now or datetime.now(timezone.utc)
    cleaned = stamp.replace("Z", "+00:00")
    try:
        then = datetime.fromisoformat(cleaned)
    except ValueError:
        return None
    if then.tzinfo is None:
        then = then.replace(tzinfo=timezone.utc)
    return max(0, (now - then).days)


def classify_ai_policy(documents: Dict[str, str]) -> Tuple[str, str]:
    """Return ('restricted'|'allowed'|'unknown', evidence snippet)."""
    for name, text in documents.items():
        if not text:
            continue
        lowered = text.lower()
        for phrase in AI_RESTRICTIVE:
            index = lowered.find(phrase)
            if index != -1:
                snippet = " ".join(text[max(0, index - 50) : index + 90].split())
                return "restricted", f"{name}: …{snippet}…"
        for phrase in AI_PERMISSIVE:
            index = lowered.find(phrase)
            if index != -1:
                snippet = " ".join(text[max(0, index - 50) : index + 90].split())
                return "allowed", f"{name}: …{snippet}…"
    return "unknown", ""


def count_claim_comments(comments: Iterable[Dict[str, Any]]) -> int:
    """How many distinct people signalled they are taking the issue."""
    claimants = set()
    for comment in comments:
        body = (comment.get("body") or "").lower()
        donor = comment.get("_author") or comment.get("user") or {}
        login = donor.get("login", "") if isinstance(donor, dict) else str(donor)
        if any(pattern in body for pattern in CLAIM_PATTERNS):
            claimants.add(login)
    return len(claimants)


def find_escrow(comments: Iterable[Dict[str, Any]], text: str = "") -> Optional[str]:
    """Return the escrow provider detected in the issue, if any."""
    haystack = (text or "").lower()
    for provider in ESCROW_TEXT:
        if provider in haystack:
            return provider
    for comment in comments:
        donor = comment.get("_author") or comment.get("user") or {}
        login = (donor.get("login", "") if isinstance(donor, dict) else str(donor)).lower()
        for bot in ESCROW_BOTS:
            if bot in login:
                return bot
    return None


def repo_health(repo: Dict[str, Any], age_days: Optional[int]) -> List[Tuple[int, str]]:
    """Legitimacy adjustments derived from repository metadata."""
    adjustments: List[Tuple[int, str]] = []
    stars = int(repo.get("stargazers_count") or 0)
    forks = int(repo.get("forks_count") or 0)

    if stars >= 500:
        adjustments.append((12, f"established repo ({stars} stars)"))
    elif stars >= 100:
        adjustments.append((8, f"real audience ({stars} stars)"))
    elif stars >= 20:
        adjustments.append((4, f"small but real repo ({stars} stars)"))
    else:
        adjustments.append((-8, f"almost no stars ({stars})"))

    if stars < 50 and forks > max(3, stars * 3):
        adjustments.append((-15, f"farm shape: {forks} forks vs {stars} stars"))

    if repo.get("archived"):
        adjustments.append((-20, "repo is archived"))
    if not repo.get("license"):
        adjustments.append((-8, "no license"))
    if age_days is not None and age_days < 30:
        adjustments.append((-6, f"repo is {age_days} days old"))
    open_issues = int(repo.get("open_issues_count") or 0)
    if open_issues > 300:
        adjustments.append((-5, f"{open_issues} open issues (backlog fire)"))
    return adjustments


def score_issue(signals: Dict[str, Any]) -> Dict[str, Any]:
    """Turn collected signals into a score, verdict and reasons."""
    score = 50
    reasons: List[Tuple[int, str]] = []

    amount = int(signals.get("amount_usd") or 0)
    if amount >= 1000:
        reasons.append((20, f"pays ${amount:,}"))
    elif amount >= 200:
        reasons.append((15, f"pays ${amount:,}"))
    elif amount >= 50:
        reasons.append((10, f"pays ${amount:,}"))
    elif amount > 0:
        reasons.append((4, f"pays only ${amount:,}"))
    else:
        reasons.append((-10, "no dollar amount in the issue"))

    if signals.get("token_reward"):
        reasons.append((-25, "reward looks token/points-denominated, not cash"))

    escrow = signals.get("escrow")
    if escrow:
        reasons.append((15, f"payout appears escrowed ({escrow})"))

    if not signals.get("is_open", True):
        reasons.append((-15, "issue is not open"))

    reasons.extend(signals.get("repo_adjustments") or [])

    comments = int(signals.get("comment_count") or 0)
    if comments <= 2:
        reasons.append((6, f"little competition ({comments} comments)"))
    elif comments <= 9:
        reasons.append((2, f"some competition ({comments} comments)"))
    elif comments <= 30:
        reasons.append((-4, f"crowded ({comments} comments)"))
    else:
        reasons.append((-10, f"very crowded ({comments} comments)"))

    open_prs = int(signals.get("open_prs") or 0)
    if open_prs:
        reasons.append((-8, f"{open_prs} open PR(s) reference this issue"))

    claimants = int(signals.get("claimants") or 0)
    if claimants:
        reasons.append((-min(12, 4 * claimants), f"{claimants} commenter(s) already claimed it"))

    age = signals.get("updated_days")
    if age is not None:
        if age <= 7:
            reasons.append((5, f"updated {age} day(s) ago"))
        elif age <= 30:
            reasons.append((2, f"updated {age} days ago"))
        elif age > 90:
            reasons.append((-8, f"stale, updated {age} days ago"))

    policy = signals.get("ai_policy")
    if policy == "restricted":
        reasons.append((-20, "repo restricts AI-generated contributions"))
    elif policy == "allowed":
        reasons.append((2, "repo explicitly allows AI contributions"))

    score += sum(delta for delta, _ in reasons)
    score = max(0, min(100, score))
    if score >= 65:
        verdict = "PURSUE"
    elif score >= 40:
        verdict = "CAUTION"
    else:
        verdict = "AVOID"

    return {
        "score": score,
        "verdict": verdict,
        "reasons": [{"delta": delta, "reason": text} for delta, text in reasons],
    }


# ---------------------------------------------------------------------------
# GitHub client (network)
# ---------------------------------------------------------------------------


class GitHubError(RuntimeError):
    pass


class GitHub:
    def __init__(self, token: Optional[str] = None, timeout: int = 25):
        self.token = token or load_token()
        self.timeout = timeout

    def _request(self, path: str) -> Any:
        url = path if path.startswith("http") else API + path
        headers = {
            "Accept": "application/vnd.github+json",
            "User-Agent": USER_AGENT,
            "X-GitHub-Api-Version": "2022-11-28",
        }
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        request = urllib.request.Request(url, headers=headers)
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                return json.loads(response.read().decode("utf-8", "replace"))
        except urllib.error.HTTPError as exc:
            if exc.code in (403, 429):
                remaining = exc.headers.get("x-ratelimit-remaining")
                raise GitHubError(
                    "GitHub rate limit or permission problem "
                    f"(HTTP {exc.code}, remaining={remaining}). "
                    "Set GITHUB_TOKEN to raise the limit."
                ) from exc
            if exc.code == 404:
                raise GitHubError(f"not found: {url}") from exc
            raise GitHubError(f"GitHub error HTTP {exc.code} for {url}") from exc
        except urllib.error.URLError as exc:
            raise GitHubError(f"network error contacting GitHub: {exc.reason}") from exc

    def issue(self, owner: str, repo: str, number: int) -> Dict[str, Any]:
        return self._request(f"/repos/{owner}/{repo}/issues/{number}")

    def repository(self, owner: str, repo: str) -> Dict[str, Any]:
        return self._request(f"/repos/{owner}/{repo}")

    def comments(self, owner: str, repo: str, number: int, limit: int = 100) -> List[Dict[str, Any]]:
        return self._request(
            f"/repos/{owner}/{repo}/issues/{number}/comments?per_page={limit}"
        )

    def open_pull_requests(self, owner: str, repo: str, number: int) -> int:
        query = f"repo:{owner}/{repo} is:pr is:open {number}"
        data = self._request("/search/issues?" + urllib.parse.urlencode({"q": query, "per_page": 1}))
        return int(data.get("total_count") or 0)

    def search_issues(self, query: str, limit: int = 10) -> List[Dict[str, Any]]:
        data = self._request(
            "/search/issues?"
            + urllib.parse.urlencode({"q": query, "per_page": min(limit, 100), "sort": "updated"})
        )
        return list(data.get("items") or [])

    def file_text(self, owner: str, repo: str, path: str) -> str:
        try:
            data = self._request(f"/repos/{owner}/{repo}/contents/{urllib.parse.quote(path)}")
        except GitHubError:
            return ""
        if not isinstance(data, dict) or data.get("encoding") != "base64":
            return ""
        import base64

        try:
            return base64.b64decode(data.get("content", "")).decode("utf-8", "replace")
        except (ValueError, TypeError):
            return ""


def load_token() -> Optional[str]:
    """First token found in the environment, then in a nearby .env file."""
    for name in TOKEN_ENV_VARS:
        value = os.environ.get(name)
        if value:
            return value.strip()
    for directory in (os.getcwd(), os.path.dirname(os.path.abspath(__file__))):
        candidate = os.path.join(directory, ".env")
        if not os.path.isfile(candidate):
            continue
        try:
            with open(candidate, encoding="utf-8") as handle:
                for line in handle:
                    line = line.strip()
                    if not line or line.startswith("#") or "=" not in line:
                        continue
                    key, value = line.split("=", 1)
                    if key.strip() in TOKEN_ENV_VARS:
                        return value.strip().strip('"').strip("'")
        except OSError:
            continue
    return None


